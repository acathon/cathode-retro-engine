/**
 * The glyph for a character code.
 *
 * Lowercase maps to its capital rather than to a blank: at seven pixels tall
 * a separate lowercase set would be mostly guesswork, and a game that prints
 * "Score" should not lose four letters to that.
 */
export function glyphFor(code: number): string[] {
  const ch = String.fromCharCode(code);
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? BLANK;
}
